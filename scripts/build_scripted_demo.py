"""Build docs/assets/demo_scripted.html: the demo page driven by SCRIPTED policies
(reference planner, objective-biased policy, biased + guard). It illustrates the
simulator's semantics and the page layout; it contains no model results.

    python scripts/build_scripted_demo.py --frozen data/frozen
"""

import argparse

from override_lab.eval import scripted
from override_lab.eval.runner import Condition, run_episodes
from override_lab.report.demo import build_demo
from override_lab.scenarios.splits import load_partition
from override_lab.sim.guard import GuardConfig

BANNER = (
    "SCRIPTED POLICIES, NOT MODELS. Rule-following planner vs the throughput-biased policy the organism is "
    "trained to imitate, with and without the guard. Shows what the page displays; contains no model results."
)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--frozen", default="data/frozen")
    ap.add_argument("--partition", default="test_family")
    ap.add_argument("--n", type=int, default=60)
    ap.add_argument("--out", default="docs/assets/demo_scripted.html")
    a = ap.parse_args()
    roots = load_partition(a.frozen, a.partition)[: a.n]
    conds = []
    for pol, guard, label in (
        (scripted.planner(), GuardConfig.off(), "scripted reference planner"),
        (scripted.biased(), GuardConfig.off(), "scripted objective-biased policy"),
        (scripted.biased(), GuardConfig.full(), "scripted objective-biased + guard"),
    ):
        tr = run_episodes(roots, pol, Condition(label, guard=guard))
        full = label + (" | guard-on" if guard.enabled else " | guard-off")
        for t in tr:
            t["condition"]["label"] = full
        conds.append({"label": full, "source": f"generated by scripts/build_scripted_demo.py from {a.frozen}/{a.partition}.jsonl", "traces": tr})
    scen = {s.root_id: (sc, (s.style, s.template_set, s.seed)) for s, sc in roots}
    build_demo(a.out, conds, scen, title="Override Lab - simulator semantics (scripted policies)", banner=BANNER, per_family=3, gallery_cap=12)
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
